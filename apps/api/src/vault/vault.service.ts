import { readFile } from 'node:fs/promises';

import { HttpService } from '@nestjs/axios';
import {
  Inject,
  Injectable,
  Logger,
  ServiceUnavailableException,
} from '@nestjs/common';
import type { ConfigType } from '@nestjs/config';
import { AxiosError } from 'axios';
import { firstValueFrom } from 'rxjs';

import { AuditService } from '../audit/audit.service';
import { vaultConfig } from './vault.config';

const RENEW_GRACE_SECONDS = 60;

/** Cred bundle for one EIRMS-registered branch. Persisted in Vault under
 *  `m-<merchantId>/data/branches/<branchId>/eirms` as kv-v2 fields. */
export interface BranchEirmsCreds {
  clientId: string;
  clientSecret: string;
  apikey: string;
}

/** Per-branch request-signing material. `privateKeyPem` is generated by us at
 *  merchant approval / branch creation (or supplied by the merchant on the BYO
 *  path); `certPem` is the verbatim INSA-issued .pem file, arriving days later
 *  via the certificate onboarding flow. Persisted at kv-v2 path
 *  `m-<merchantId>/data/branches/<branchId>/signing`. Either field may be null
 *  during the intermediate state where the key exists but the cert hasn't been
 *  uploaded yet. */
export interface BranchSigningMaterial {
  privateKeyPem: string | null;
  certPem: string | null;
}

/** Subset of the kv-v2 read response we actually use. */
interface KvReadResponse<T = Record<string, string>> {
  data?: {
    data?: T;
  };
}

interface VaultAuthResponse {
  auth: {
    client_token: string;
    lease_duration: number;
    renewable: boolean;
  };
}

interface VaultErrorBody {
  errors?: string[];
}

/** Anything we need to redact before passing a body to AuditService. The kv-v2
 *  write envelope is `{ data: { clientId, clientSecret, apikey } }`; the
 *  existing redactor would already replace `clientSecret`/`apikey`, but it
 *  doesn't know that `clientId` is also sensitive here. We collapse the whole
 *  `data` blob to a placeholder instead. */
const REDACTED_DATA = { data: '[redacted]' };

@Injectable()
export class VaultService {
  private readonly logger = new Logger(VaultService.name);
  private token: string | null = null;
  private tokenExpiresAt = 0;
  private inFlightLogin: Promise<string> | null = null;

  constructor(
    @Inject(vaultConfig.KEY)
    private readonly config: ConfigType<typeof vaultConfig>,
    private readonly http: HttpService,
    private readonly audit: AuditService,
  ) {}

  // ----- public KV API ------------------------------------------------------

  /** Persist a branch's EIRMS creds. Creates the merchant's kv-v2 mount on
   *  first write — callers don't need to think about provisioning. */
  async writeBranchCreds(
    merchantId: string,
    branchId: string,
    creds: BranchEirmsCreds,
  ): Promise<void> {
    await this.ensureMerchantMount(merchantId);
    const path = this.branchCredsPath(merchantId, branchId);
    await this.recordedRequest(
      'POST',
      `/v1/${path}`,
      { data: creds },
      {
        action: 'vault.kv.write',
        auditPath: path,
        // Never let real cred values reach the audit row — even the redactor
        // doesn't know `clientId` is sensitive in this context.
        auditRequestBody: REDACTED_DATA,
      },
    );
  }

  /** Read a branch's EIRMS creds. Returns `null` if the secret doesn't
   *  exist (kv-v2 returns 404 either for never-written or soft-deleted). */
  async readBranchCreds(
    merchantId: string,
    branchId: string,
  ): Promise<BranchEirmsCreds | null> {
    const path = this.branchCredsPath(merchantId, branchId);
    try {
      const body = await this.recordedRequest<KvReadResponse<BranchEirmsCreds>>(
        'GET',
        `/v1/${path}`,
        undefined,
        { action: 'vault.kv.read', auditPath: path },
      );
      const data = body.data?.data ?? null;
      if (!data || !data.clientId || !data.clientSecret || !data.apikey) {
        return null;
      }
      return {
        clientId: data.clientId,
        clientSecret: data.clientSecret,
        apikey: data.apikey,
      };
    } catch (err) {
      if (err instanceof ServiceUnavailableException && isNotFound(err)) {
        return null;
      }
      throw err;
    }
  }

  /** Soft-delete the latest version of the branch's creds. Used when an admin
   *  blanks the creds via the merchants API. Idempotent — a 404 (already
   *  gone) is treated as success. */
  async deleteBranchCreds(merchantId: string, branchId: string): Promise<void> {
    const path = this.branchCredsPath(merchantId, branchId);
    try {
      await this.recordedRequest('DELETE', `/v1/${path}`, undefined, {
        action: 'vault.kv.delete',
        auditPath: path,
      });
    } catch (err) {
      if (err instanceof ServiceUnavailableException && isNotFound(err)) return;
      throw err;
    }
  }

  /** Boolean-per-field view of what's stored, for the merchants controller's
   *  `eirmsClientIdSet`/`eirmsClientSecretSet`/`eirmsApikeySet` flags. We
   *  write the three fields together but check each independently so the UI
   *  reflects reality if one is later individually cleared. */
  async getBranchCredFlags(
    merchantId: string,
    branchId: string,
  ): Promise<{ clientId: boolean; clientSecret: boolean; apikey: boolean }> {
    try {
      const creds = await this.readBranchCreds(merchantId, branchId);
      if (!creds) {
        return { clientId: false, clientSecret: false, apikey: false };
      }
      return {
        clientId: !!creds.clientId,
        clientSecret: !!creds.clientSecret,
        apikey: !!creds.apikey,
      };
    } catch (err) {
      // Failing the entire branch list because Vault is briefly unreachable
      // is the wrong behaviour — surface "unknown" by returning false, which
      // the UI already renders as "not configured", and log loudly.
      this.logger.warn(
        `Vault unreachable while reading cred flags for ${merchantId}/${branchId}: ${(err as Error).message}`,
      );
      return { clientId: false, clientSecret: false, apikey: false };
    }
  }

  // ----- per-branch signing material ---------------------------------------

  /** Write the branch's request-signing material. Callers compose the full
   *  `{ privateKeyPem, certPem }` blob — this method does NOT merge with what
   *  exists in Vault, so if you're adding a cert to an existing key, read
   *  first and pass both values. */
  async writeBranchSigning(
    merchantId: string,
    branchId: string,
    material: BranchSigningMaterial,
  ): Promise<void> {
    await this.ensureMerchantMount(merchantId);
    const path = this.branchSigningPath(merchantId, branchId);
    await this.recordedRequest(
      'POST',
      `/v1/${path}`,
      { data: material },
      {
        action: 'vault.kv.write',
        auditPath: path,
        // The private key + cert are both sensitive PII once combined with a
        // TIN — never let real bytes reach the audit table.
        auditRequestBody: REDACTED_DATA,
      },
    );
  }

  /** Read the branch's signing material. Returns `null` when the secret
   *  doesn't exist (never-written or soft-deleted). */
  async readBranchSigning(
    merchantId: string,
    branchId: string,
  ): Promise<BranchSigningMaterial | null> {
    const path = this.branchSigningPath(merchantId, branchId);
    try {
      const body = await this.recordedRequest<
        KvReadResponse<BranchSigningMaterial>
      >('GET', `/v1/${path}`, undefined, {
        action: 'vault.kv.read',
        auditPath: path,
      });
      const data = body.data?.data ?? null;
      if (!data) return null;
      return {
        privateKeyPem: data.privateKeyPem ?? null,
        certPem: data.certPem ?? null,
      };
    } catch (err) {
      if (err instanceof ServiceUnavailableException && isNotFound(err)) {
        return null;
      }
      throw err;
    }
  }

  /** Soft-delete the signing material. Used only on branch teardown — the
   *  normal renewal path overwrites in place. */
  async deleteBranchSigning(
    merchantId: string,
    branchId: string,
  ): Promise<void> {
    const path = this.branchSigningPath(merchantId, branchId);
    try {
      await this.recordedRequest('DELETE', `/v1/${path}`, undefined, {
        action: 'vault.kv.delete',
        auditPath: path,
      });
    } catch (err) {
      if (err instanceof ServiceUnavailableException && isNotFound(err)) return;
      throw err;
    }
  }

  /** UI flag-view: has a key, has a cert. Both false when Vault is unreachable
   *  (same graceful-degrade posture as {@link getBranchCredFlags}). */
  async getBranchSigningFlags(
    merchantId: string,
    branchId: string,
  ): Promise<{ privateKey: boolean; cert: boolean }> {
    try {
      const material = await this.readBranchSigning(merchantId, branchId);
      if (!material) return { privateKey: false, cert: false };
      return {
        privateKey: !!material.privateKeyPem,
        cert: !!material.certPem,
      };
    } catch (err) {
      this.logger.warn(
        `Vault unreachable while reading signing flags for ${merchantId}/${branchId}: ${(err as Error).message}`,
      );
      return { privateKey: false, cert: false };
    }
  }

  // ----- mount --------------------------------------------------------------

  /** Idempotent: enables the `m-<merchantId>` kv-v2 mount if it isn't already
   *  present. Vault returns 400 with "path is already in use" on a re-enable;
   *  we treat that as success. */
  async ensureMerchantMount(merchantId: string): Promise<void> {
    const mount = this.mountName(merchantId);
    try {
      await this.recordedRequest(
        'POST',
        `/v1/sys/mounts/${mount}`,
        {
          type: 'kv',
          options: { version: '2' },
          description: `EIRMS credentials for merchant ${merchantId}`,
        },
        { action: 'vault.mount.enable', auditPath: `sys/mounts/${mount}` },
      );
    } catch (err) {
      if (err instanceof ServiceUnavailableException && isAlreadyInUse(err)) {
        return;
      }
      throw err;
    }
  }

  // ----- paths --------------------------------------------------------------

  private mountName(merchantId: string): string {
    // Merchant IDs are cuids (alpha-num), so they're already safe to embed in
    // a Vault mount name. Defence-in-depth: reject anything else loudly so a
    // future change in id shape doesn't silently produce an unreadable path.
    if (!/^[a-zA-Z0-9_-]+$/.test(merchantId)) {
      throw new Error(`Refusing to derive Vault mount from id: ${merchantId}`);
    }
    return `m-${merchantId}`;
  }

  private branchCredsPath(merchantId: string, branchId: string): string {
    if (!/^[a-zA-Z0-9_-]+$/.test(branchId)) {
      throw new Error(`Refusing to derive Vault path from id: ${branchId}`);
    }
    return `${this.mountName(merchantId)}/data/branches/${branchId}/eirms`;
  }

  private branchSigningPath(merchantId: string, branchId: string): string {
    if (!/^[a-zA-Z0-9_-]+$/.test(branchId)) {
      throw new Error(`Refusing to derive Vault path from id: ${branchId}`);
    }
    return `${this.mountName(merchantId)}/data/branches/${branchId}/signing`;
  }

  // ----- auth ---------------------------------------------------------------

  private async ensureToken(): Promise<string> {
    if (
      this.token &&
      Date.now() < this.tokenExpiresAt - RENEW_GRACE_SECONDS * 1000
    ) {
      return this.token;
    }
    if (this.inFlightLogin) return this.inFlightLogin;
    this.inFlightLogin = this.login().finally(() => {
      this.inFlightLogin = null;
    });
    return this.inFlightLogin;
  }

  private async login(): Promise<string> {
    const [roleId, secretId] = await Promise.all([
      this.readFileTrim(this.config.roleIdFile),
      this.readFileTrim(this.config.secretIdFile),
    ]);
    const url = `${this.config.address}/v1/auth/approle/login`;
    try {
      const response = await firstValueFrom(
        this.http.post<VaultAuthResponse>(
          url,
          { role_id: roleId, secret_id: secretId },
          { headers: { 'Content-Type': 'application/json' } },
        ),
      );
      const auth = response.data?.auth;
      if (!auth?.client_token) {
        throw new ServiceUnavailableException(
          'Vault AppRole login returned no client_token.',
        );
      }
      this.token = auth.client_token;
      this.tokenExpiresAt = Date.now() + (auth.lease_duration || 3600) * 1000;
      return this.token;
    } catch (err) {
      this.token = null;
      this.tokenExpiresAt = 0;
      throw this.translateError(err, 'auth/approle/login');
    }
  }

  private async readFileTrim(path: string): Promise<string> {
    try {
      const raw = await readFile(path, 'utf-8');
      const trimmed = raw.trim();
      if (!trimmed) {
        throw new Error(`Vault credential file empty: ${path}`);
      }
      return trimmed;
    } catch (err) {
      throw new ServiceUnavailableException(
        `Vault credential file unreadable (${path}): ${(err as Error).message}`,
      );
    }
  }

  // ----- transport ----------------------------------------------------------

  /** One round-trip to Vault + a matching OUTBOUND audit row. Splitting this
   *  out keeps the audit story uniform (success + error both get a row) and
   *  centralises error → ServiceUnavailableException translation. */
  private async recordedRequest<T = unknown>(
    method: 'GET' | 'POST' | 'PUT' | 'DELETE',
    path: string,
    body: unknown,
    audit: {
      action: string;
      auditPath: string;
      /** Override the body recorded in the audit row (used to elide secrets). */
      auditRequestBody?: unknown;
    },
  ): Promise<T> {
    const url = `${this.config.address}${path}`;
    const startedAt = Date.now();
    const token = await this.ensureToken();
    try {
      const response = await firstValueFrom(
        this.http.request<T>({
          method,
          url,
          data: body,
          headers: {
            'X-Vault-Token': token,
            'Content-Type': 'application/json',
          },
        }),
      );
      void this.audit.recordOutbound({
        action: audit.action,
        path: audit.auditPath,
        requestBody: audit.auditRequestBody ?? body,
        // Read paths return the actual secret in the response — never persist
        // that. Other actions return metadata, not secrets, but defaulting to
        // null keeps the audit table consistently safe.
        responseBody: null,
        statusCode: response.status,
        success: true,
        durationMs: Date.now() - startedAt,
      });
      return response.data;
    } catch (err) {
      const status =
        err instanceof AxiosError
          ? (err.response?.status ?? undefined)
          : undefined;
      void this.audit.recordOutbound({
        action: audit.action,
        path: audit.auditPath,
        requestBody: audit.auditRequestBody ?? body,
        responseBody: null,
        statusCode: typeof status === 'number' ? status : undefined,
        success: false,
        errorMessage: (err as Error).message,
        durationMs: Date.now() - startedAt,
      });
      throw this.translateError(err, audit.auditPath);
    }
  }

  private translateError(
    err: unknown,
    path: string,
  ): ServiceUnavailableException {
    if (err instanceof ServiceUnavailableException) return err;
    if (err instanceof AxiosError) {
      const status = err.response?.status ?? 'network';
      const errBody = err.response?.data as VaultErrorBody | undefined;
      const detail =
        (errBody?.errors && errBody.errors.join('; ')) || err.message;
      return new ServiceUnavailableException(
        `Vault ${path} failed (${status}): ${detail}`,
      );
    }
    return new ServiceUnavailableException(
      `Vault ${path} failed: ${(err as Error).message}`,
    );
  }
}

/** Vault returns 404 for "no such secret" — including soft-deleted versions. */
function isNotFound(err: ServiceUnavailableException): boolean {
  return err.message.includes('failed (404)');
}

/** Idempotent mount-enable signal. Vault wraps the message in an `errors`
 *  array; our translator joins them, so we just look for the substring. */
function isAlreadyInUse(err: ServiceUnavailableException): boolean {
  return err.message.toLowerCase().includes('path is already in use');
}
